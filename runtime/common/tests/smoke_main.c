/* runtime/arm/tests/smoke_main.c — ARMv6 Linux smoke test of the runtime + SDL2 + LLASM helpers.
 *
 * Built as a dynamically linked ELF against the extracted Raspberry Pi OS Bookworm armhf sysroot
 * and executed with `qemu-arm-static -cpu arm1176 -L build/sysroot`. What it proves, in order:
 *
 *   1. the low-address contract (every guest-visible pointer < 0x80000000, so `~ptr` is negative
 *      exactly as storm.dll assumes) on a plain 32-bit ARM Linux process, without MAP_32BIT;
 *   2. a `_cpu` object, guest stack and TEB live in that arena and are reachable through guest
 *      VAs (this is what makes PTR2REG(&st_result) work);
 *   3. guest code generated by SRW/LLASM runs the *vendored* SR helper implementations under
 *      ARMv6/VFPv2: 64-bit division, 32-bit signed division, x87 double multiply, rep movsd,
 *      repe cmpsb, fs:[0x34] round-trip;
 *   4. the import bridge: a 1-argument stdcall stub returns through the guest stack with esp
 *      restored (the harness re-checks esp and the stack canary), and GetLastError reads the
 *      TEB written by the guest through x86_write_fs_dword;
 *   5. SDL2 (2.26.5 from the Pi OS image) initialises, creates a window surface and accepts
 *      pixel writes with the dummy video driver.
 */
#include "cpu_llasm.h"
#include "game_memory_arm.h"
#include "x86_helpers.h"
#include "bridge_arm.h"
#include "elf_support_arm.h"

#include <SDL2/SDL.h>

#include <stdint.h>
#include <string.h>

extern long write(int fd, const void *buf, unsigned long n);
extern void _exit(int);

#define IMAGE_BASE 0x00400000u
#define IMAGE_SIZE 0x00010000u

/* guest scratch addresses used by smoke_guest.llasm */
#define G_DIV_EAX   0x00401000u
#define G_DIV_EDX   0x00401004u
#define G_IDIV_EAX  0x00401008u
#define G_IDIV_EDX  0x0040100Cu
#define G_DOUBLE    0x00401010u
#define G_CMPS_ECX  0x00401018u
#define G_FS_VALUE  0x0040101Cu
#define G_PROBE     0x00401020u
#define G_GLE       0x00401024u
#define G_CANARY    0x00401028u
#define G_DBL_IN1   0x00401030u
#define G_DBL_IN2   0x00401038u
#define G_MOVSRC    0x00401100u
#define G_MOVDST    0x00401110u

extern void c_smoke_guest(_cpu *cpu);      /* ccc wrapper emitted by llasm (see cpu_llasm.h) */
extern void raw_guest(_cpu *cpu);          /* bare fastcc body: entered with run_raw */
extern void armtest_probe(void);           /* bridge stub generated from bridge_table.def */

static int g_fail;

static void out(const char *s) { (void) write(1, s, strlen(s)); }

static void out_hex(uint32_t v) {
    static const char hx[] = "0123456789abcdef";
    char b[11];
    int i;
    b[0] = '0'; b[1] = 'x';
    for (i = 0; i < 8; ++i) b[2 + i] = hx[(v >> (28 - 4 * i)) & 0xF];
    b[10] = '\n';
    (void) write(1, b, 11);
}

static uint32_t rd32(uint32_t va) {
    uint32_t v;
    memcpy(&v, (const void *) (unsigned long) va, 4);
    return v;
}

static void expect32(const char *what, uint32_t got, uint32_t want) {
    if (got == want) {
        out("  ok   "); out(what); out("\n");
    } else {
        out("  FAIL "); out(what); out(" got="); out_hex(got);
        out("      want="); out_hex(want);
        g_fail++;
    }
}

int main(void) {
    _cpu *cpu;
    uint32_t esp_before, esp_after;
    double d;

    out("[smoke] runtime ARMv6: arena, TEB, guest LLASM helpers, bridge, SDL2\n");

    /* ---- 1) low address space ---- */
    if (arm_arena_init() != 0) { out("  FAIL arena\n"); return 10; }
    if (arm_map_at(IMAGE_BASE, IMAGE_SIZE) != 0) { out("  FAIL immagine a 0x00400000\n"); return 11; }
    if (arm_selftest_low() != 0) { out("  FAIL selftest ~ptr\n"); return 12; }

    expect32("arm_alloc_low restituisce memoria sotto 0x80000000",
             (uint32_t) (uintptr_t) arm_alloc_low(16, 8) < ARM_LOW_LIMIT ? 1u : 0u, 1u);

    /* ---- 2) test data in guest memory (absolute VAs, as translated code expects) ---- */
    {
        double in1 = 1.5, in2 = 2.0;
        static const unsigned char src[16] = "ABCDEFGHIJKLMNO";
        memcpy((void *) (unsigned long) G_DBL_IN1, &in1, 8);
        memcpy((void *) (unsigned long) G_DBL_IN2, &in2, 8);
        memcpy((void *) (unsigned long) G_MOVSRC, src, 16);
        memset((void *) (unsigned long) G_MOVDST, 0, 16);
        memset((void *) (unsigned long) G_CANARY, 0xCC, 4);
    }

    /* ---- 3) CPU + guest run ---- */
    cpu = cpu_llasm_create(0x00040000u);
    if (!cpu) { out("  FAIL cpu_llasm_create\n"); return 13; }
    expect32("cpu in zona bassa", (uint32_t) (uintptr_t) cpu < ARM_LOW_LIMIT ? 1u : 0u, 1u);
    expect32("TEB emulato in zona bassa", arm_teb_base() < ARM_LOW_LIMIT && arm_teb_base() != 0 ? 1u : 0u, 1u);
    expect32("eflags IF impostato", (cpu->_eflags & 0x200u) ? 1u : 0u, 1u);
    expect32("x87 cw di default", cpu->_st_cw, 0x037Fu);

    esp_before = cpu->_esp;
    if (cpu_llasm_run(cpu, c_smoke_guest) != 0) {
        out("  FAIL cpu_llasm_run (l'entry e' tornata invece di passare dal sentinella)\n");
        g_fail++;
    }
    esp_after = cpu->_esp;
    /* The ccc wrapper pushes __return_procedure and the guest's final `ret` pops it: the guest
     * stack must be back where it started (a stdcall mismatch would show up as a delta here). */
    expect32("esp del guest ripristinato dal ret", esp_after, esp_before);

    /* ---- 4) results of the guest code ---- */
    expect32("div 2^32 / 7 -> quoziente", rd32(G_DIV_EAX), 613566756u);
    expect32("div 2^32 / 7 -> resto", rd32(G_DIV_EDX), 4u);
    expect32("idiv 100 / 7 -> quoziente", rd32(G_IDIV_EAX), 14u);
    expect32("idiv 100 / 7 -> resto", rd32(G_IDIV_EDX), 2u);

    memcpy(&d, (const void *) (unsigned long) G_DOUBLE, 8);
    if (d == 3.0) out("  ok   x87 1.5 * 2.0 == 3.0\n");
    else { out("  FAIL x87 1.5 * 2.0 (double inatteso)\n"); g_fail++; }

    expect32("rep movsd copia 16 byte", memcmp((const void *) (unsigned long) G_MOVSRC,
                                               (const void *) (unsigned long) G_MOVDST, 16) == 0 ? 1u : 0u, 1u);
    expect32("repe cmpsb su blocchi uguali -> ecx 0", rd32(G_CMPS_ECX), 0u);
    expect32("fs:[0x34] round-trip", rd32(G_FS_VALUE), 0x1234u);
    expect32("import stdcall 21*2+1", rd32(G_PROBE), 43u);
    expect32("GetLastError via bridge legge il TEB", rd32(G_GLE), 0x1234u);
    expect32("canary dello stack guest intatto", rd32(G_CANARY), 0xCCCCCCCCu);

    /* ---- 4b) bare routine entered through the sentinel ----
     * `raw_guest` has no wrapper, so the runtime must synthesise its return address. */
    {
        int rc;
        cpu->_eax = 0;
        rc = cpu_llasm_run_raw(cpu, raw_guest);
        expect32("raw: ritorno via sentinella", (uint32_t) rc, 0u);
        expect32("raw: eax scritto dal guest", cpu->_eax, 0x5A5A5A5Au);
    }

    /* ---- 5) bridge table inventory ---- */
    out("[smoke] bridge: ");
    { char n[4]; unsigned c = g_bridge_count; int i = 0, k;
      char t[4]; if (!c) t[i++] = '0'; while (c) { t[i++] = (char) ('0' + c % 10); c /= 10; }
      for (k = 0; k < i; ++k) n[k] = t[i - 1 - k];
      n[i] = 0; out(n); }
    out(" import nel bridge (0 UNK: ");
    expect32("nessun UNK nella tabella di prova", arm_bridge_unk_count(), 0u);
    out("); ordinali storm nella tabella generata: ");
    expect32("ordinale 101 di storm risolto (VA tradotta)", arm_bridge_ordinal_va(101u) != 0 ? 1u : 0u, 1u);

    /* ---- 5b) module/proc lookup: what the x86 runtime did through a real IAT ---- */
    expect32("GetModuleHandleA(NULL) = 0x400000",
             (uint32_t) (uintptr_t) reasm_elf_GetModuleHandleA(0), 0x00400000u);
    expect32("GetModuleHandleA(\"storm.dll\") = 0x15000000",
             (uint32_t) (uintptr_t) reasm_elf_GetModuleHandleA("storm.dll"), 0x15000000u);
    expect32("GetProcAddress per nome -> stub del bridge",
             (uint32_t) (uintptr_t) reasm_elf_GetProcAddress(0, "armtest_probe") ==
             (uint32_t) (uintptr_t) &armtest_probe ? 1u : 0u, 1u);
    expect32("GetProcAddress(\"#101\") -> VA tradotta di storm",
             (uint32_t) (uintptr_t) reasm_elf_GetProcAddress(0, "#101"),
             arm_bridge_ordinal_va(101u));
    expect32("GetProcAddress ordinal_73746f726d2e646c6c_101",
             (uint32_t) (uintptr_t) reasm_elf_GetProcAddress(0, "ordinal_73746f726d2e646c6c_101"),
             arm_bridge_ordinal_va(101u));

    if (cpu_llasm_install_crash_handler(cpu) == 0)
        out("  ok   handler di crash installato (SIGSEGV/SIGBUS -> eip/esp/eax guest)\n");

    /* ---- 6) SDL2 from the Pi OS sysroot, dummy video driver ---- */
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_TIMER) != 0) {
        out("  FAIL SDL_Init: "); out(SDL_GetError()); out("\n");
        g_fail++;
    } else {
        SDL_version lv;
        SDL_Window *win;
        SDL_Surface *surf;
        SDL_GetVersion(&lv);
        out("[smoke] SDL ");
        { char b[12]; int i = 0, v = lv.minor; char t[4]; int k = 0;
          if (!v) t[k++] = '0'; while (v) { t[k++] = (char) ('0' + v % 10); v /= 10; }
          for (i = 0; i < k; ++i) b[i] = t[k - 1 - i]; b[k] = 0; out("2."); out(b); out(" driver="); }
        out(SDL_GetCurrentVideoDriver() ? SDL_GetCurrentVideoDriver() : "(nessuno)");
        out("\n");
        expect32("SDL versione >= 2.0.12", (lv.major == 2 && lv.minor >= 0) ? 1u : 0u, 1u);

        win = SDL_CreateWindow("armv6-smoke", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
                               320, 240, SDL_WINDOW_SHOWN);
        if (!win) { out("  FAIL SDL_CreateWindow: "); out(SDL_GetError()); out("\n"); g_fail++; }
        else {
            surf = SDL_GetWindowSurface(win);
            if (!surf) { out("  FAIL SDL_GetWindowSurface: "); out(SDL_GetError()); out("\n"); g_fail++; }
            else {
                uint32_t *px = (uint32_t *) surf->pixels;
                SDL_Rect r;
                r.x = 4; r.y = 4; r.w = 8; r.h = 8;
                SDL_FillRect(surf, &r, SDL_MapRGB(surf->format, 0x11, 0x22, 0x33));
                SDL_UpdateWindowSurface(win);
                expect32("superficie con pixel scrivibili", px != 0 ? 1u : 0u, 1u);
                expect32("SDL_MapRGB coerente", (uint32_t) SDL_MapRGB(surf->format, 0xFF, 0x00, 0x00) != 0xFFFFFFFFu ? 1u : 0u, 1u);
            }
            SDL_DestroyWindow(win);
        }
        SDL_Quit();
    }

    if (g_fail) { out("[smoke] ESITO: FALLITO\n"); return 1; }
    out("[smoke] ESITO: PASS\n");
    return 0;
}
