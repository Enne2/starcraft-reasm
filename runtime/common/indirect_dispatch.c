/* runtime/arm/indirect_dispatch.c — see indirect_dispatch.h for the oracle and the contract.
 *
 * The resolve path is deliberately allocation-free and lock-free: it runs on every indirect edge
 * of the translated code, including loop-heavy vtables, so the fast path is a 4096-entry
 * direct-mapped cache keyed by (target >> 2). A miss does a binary search over the sorted table
 * emitted by tools/dispatch-ir.py (one entry per translated procedure).
 *
 * Resolution order and why it is unambiguous:
 *   1. exact guest VA in the table  -> its translated entry (the only way a *guest* address is
 *      accepted);
 *   2. value inside the port's own code window [reasm_text_lo, reasm_text_hi) -> branch as-is.
 *      Both bounds come from the link (build/lift-full/entry/guest_data.ld, generated by
 *      tools/build-entry-obj.sh): they are ADDR(.text)/SIZEOF(.text), NOT __executable_start/
 *      etext, because with the guest data mapped at its original VAs the generic symbols span
 *      guest addresses too (measured: __executable_start=0x00010000, etext=0x18ADF530, which
 *      made the CRT initialiser pointer 0x004060C0 look like one of our own addresses and the
 *      port branched into guest memory — report §2).
 *   3. anything else -> reasm_indirect_unresolved(): a named stop with the target, the caller VA
 *      reverse-mapped through the same table, and the guest CPU state.
 *
 * Step 1 and step 2 can only be confused if a translated guest VA is numerically equal to one of
 * our own code addresses. tools/dispatch-ir.py checks that after the link and fails the build if
 * it ever happens (see `--check-overlap`), so the order above cannot mask a mistranslation.
 */
#include "indirect_dispatch.h"
#include "cpu_llasm.h"
#include "game_memory_arm.h"

#include <stdint.h>
#include <stdio.h>

extern long write(int fd, const void *buf, unsigned long n);
extern void _exit(int);

/* Bounds of the port's own text, defined by the linker script guest_data.ld
 * (reasm_text_lo = ADDR(.text), reasm_text_hi = ADDR(.text) + SIZEOF(.text)). */
extern char reasm_text_lo[];
extern char reasm_text_hi[];
#if defined(__i386__)
/* i686 llc lowers IR continuations to native addresses inside these two guest-code
 * sections. Unlike the port .text, they are valid return targets from x86 bridge thunks. */
extern char reasm_exe_code_lo[], reasm_exe_code_hi[];
extern char reasm_storm_code_lo[], reasm_storm_code_hi[];
#endif

/* Il target dell'arco indiretto e l'ESP dell'arco vivono in `_cpu` (`._ind_target`, `._ind_esp`,
 * offset 144/148): erano global e con due thread tradotti il target veniva sovrascritto fra lo
 * store emesso dall'IR e la load in reasm_indirect.S (work/link/REPORT-flash-heap.md §5). */

static uint32_t g_arm_lo, g_arm_hi;
#if defined(__i386__)
static uint32_t g_exe_code_lo, g_exe_code_hi;
static uint32_t g_storm_code_lo, g_storm_code_hi;
#endif

/* Anello diagnostico: per ogni arco indiretto (target, ESP, parola in cima allo stack emulato
 * *prima* dell'arco). Con questi tre valori lo stop si classifica da solo:
 *   word == target            -> l'arco e' una `ret`/pop: il VA incriminato ERA sullo stack;
 *   word in [text_lo,text_hi) -> l'arco e' un `call`: word e' la continuazione pushata, e il suo
 *                                reverse-map da' il VA guest subito DOPO la call (il sito);
 *   altrimenti                -> l'arco e' un `call [mem]`/`call reg` con continuazione anomala.
 * Costo nel percorso normale: tre store per arco (nessuna syscall, nessun ramo in piu'). */
typedef struct { uint32_t target, esp, word, wordm1; } reasm_edge;

#define RING_SIZE 8u
static __thread reasm_edge g_ring[RING_SIZE];
static __thread unsigned g_ring_i;

#define CACHE_BITS 12
#define CACHE_SIZE (1u << CACHE_BITS)
typedef struct { uint32_t key; void *val; } reasm_ind_cache_entry;

void reasm_dispatch_init(void) {
    g_arm_lo = (uint32_t) (unsigned long) reasm_text_lo;
    g_arm_hi = (uint32_t) (unsigned long) reasm_text_hi;
#if defined(__i386__)
    g_exe_code_lo = (uint32_t) (unsigned long) reasm_exe_code_lo;
    g_exe_code_hi = (uint32_t) (unsigned long) reasm_exe_code_hi;
    g_storm_code_lo = (uint32_t) (unsigned long) reasm_storm_code_lo;
    g_storm_code_hi = (uint32_t) (unsigned long) reasm_storm_code_hi;
#endif
}

static void *cache_put(uint32_t key, void *val) {
    unsigned i = (key >> 2) & (CACHE_SIZE - 1u);
    _cpu *cpu = cpu_llasm_current();
    reasm_ind_cache_entry *cache = cpu ? (reasm_ind_cache_entry *)cpu->_ind_cache : 0;
    if (cache) {
        cache[i].val = 0;
        cache[i].key = key;
        cache[i].val = val;
    }
    return val;
}

void *reasm_indirect_resolve(uint32_t target) {
    unsigned i;
    uint32_t lo, hi;

    if (!target) return 0;

    /* Cache hit precedes TLS lookup, guest-range checks, reads and ring access. */
    i = (target >> 2) & (CACHE_SIZE - 1u);
    {
        _cpu *cpu = cpu_llasm_current();
        reasm_ind_cache_entry *cache = cpu ? (reasm_ind_cache_entry *)cpu->_ind_cache : 0;
        if (cache && cache[i].key == target && cache[i].val) return cache[i].val;
    }

    /* Cache misses retain the diagnostic trail. TLS keeps independent histories per CPU thread. */
    {
        reasm_edge *e = &g_ring[g_ring_i++ & (RING_SIZE - 1u)];
        _cpu *cpu = cpu_llasm_current();
        uint32_t esp = cpu ? cpu->_ind_esp : 0;
        e->target = target;
        e->esp = esp;
        e->word = (esp && arm_va_is_mapped(esp, 4)) ? cpu_llasm_read32(esp) : 0;
        e->wordm1 = (esp >= 4u && arm_va_is_mapped(esp - 4u, 4)) ? cpu_llasm_read32(esp - 4u) : 0;
    }

    lo = 0;
    hi = reasm_va_map_n;
    while (lo < hi) {
        uint32_t mid = (lo + hi) >> 1;
        uint32_t va = reasm_va_va[mid];
        if (va < target) {
            lo = mid + 1u;
        } else if (va > target) {
            hi = mid;
        } else {
            return cache_put(target, reasm_va_fn[mid]);
        }
    }

    if (target >= g_arm_lo && target < g_arm_hi)
        return cache_put(target, (void *) (unsigned long) target);
#if defined(__i386__)
    /* The native i686 translation uses host addresses for LLASM labels. A Win32 bridge
     * pops its continuation from the emulated stack and returns it through this resolver;
     * such a label is not a VA-table entry or port .text, but must be an executable label
     * inside one of the two precisely linked translated-code sections. Do not widen this to
     * the gap between sections or to general process mappings (D19: no guessed targets). */
    if ((target >= g_exe_code_lo && target < g_exe_code_hi) ||
        (target >= g_storm_code_lo && target < g_storm_code_hi))
        return cache_put(target, (void *) (unsigned long) target);
#endif

    return 0;
}

/* ---- declared stop ---------------------------------------------------------------------- */

static void put(const char *s) {
    unsigned n = 0;
    while (s[n]) ++n;
    (void) write(2, s, n);
}

static void put_hex(uint32_t v) {
    static const char hx[] = "0123456789ABCDEF";
    char b[11];
    int i;
    b[0] = '0'; b[1] = 'x';
    for (i = 0; i < 8; ++i) b[2 + i] = hx[(v >> (28 - 4 * i)) & 0xF];
    b[10] = '\n';
    (void) write(2, b, sizeof b);
}

/* Stop-path-only JIT diagnostic. Do not dereference an arbitrary indirect target: first
 * establish from /proc/self/maps that the complete range is readable. */
static int proc_range_readable(uint32_t target, uint32_t len) {
    FILE *f = fopen("/proc/self/maps", "r");
    char line[512], perms[5];
    unsigned long lo, hi;
    int ok = 0;
    if (!f) return 0;
    while (fgets(line, sizeof line, f)) {
        if (sscanf(line, "%lx-%lx %4s", &lo, &hi, perms) == 3 &&
            perms[0] == 'r' && (unsigned long)target >= lo &&
            (unsigned long)target + len <= hi) {
            ok = 1;
            break;
        }
    }
    fclose(f);
    return ok;
}

static void dump_jit_bytes(uint32_t target) {
    static const char hx[] = "0123456789ABCDEF";
    char line[16 * 3 + 1];
    const unsigned char *p = (const unsigned char *)(unsigned long)target;
    unsigned i;
    if (!proc_range_readable(target, 64)) {
        put("  [jit] primi 64 byte: non leggibili secondo /proc/self/maps\n");
        return;
    }
    put("  [jit] primi 64 byte a "); put_hex(target);
    for (i = 0; i < 64; ++i) {
        line[(i % 16) * 3] = hx[p[i] >> 4];
        line[(i % 16) * 3 + 1] = hx[p[i] & 15];
        line[(i % 16) * 3 + 2] = (i % 16 == 15 || i == 63) ? '\n' : ' ';
        if ((i % 16) == 15 || i == 63) (void)write(2, line, 49);
    }
}

/* Reverse map: which guest VA does this host entry belong to? Linear, used only on the stop
 * path (a table of ~9e4 entries). */
static uint32_t va_of_fn(uint32_t fn) {
    uint32_t i;
    if (!fn) return 0;
    for (i = 0; i < reasm_va_map_n; ++i)
        if ((uint32_t) (unsigned long) reasm_va_fn[i] == fn) return reasm_va_va[i];
    return 0;
}

void reasm_indirect_unresolved(void *cpuptr, uint32_t target) {
    _cpu *cpu = (_cpu *) cpuptr;
    uint32_t ret_arm = cpu ? cpu_llasm_read32(cpu->_esp) : 0;

    put("[arm-dispatch] STOP: salto indiretto a un indirizzo non tradotto\n");
    put("  target    = "); put_hex(target);
    if (target >= 0x20000000u) dump_jit_bytes(target);
    put("  in mappa  = "); put_hex(cpu ? (arm_va_is_mapped(target, 4) ? 1u : 0u) : 0u);
    if (cpu) {
        put("  eip chiamante = "); put_hex(va_of_fn(ret_arm));
        put("  ret (ARM) = "); put_hex(ret_arm);
        put("  esp       = "); put_hex(cpu->_esp);
        put("  eax       = "); put_hex(cpu->_eax);
        put("  ecx       = "); put_hex(cpu->_ecx);
        put("  edx       = "); put_hex(cpu->_edx);
        /* ebx/esi/edi/ebp: un `jmp reg` verso un valore non tradotto arriva qui con la sorgente in
         * uno di questi registri (eax/ecx/edx stampati sopra non bastano: misurato su
         * 0x407828, work/link/REPORT-flash-storm.md §2). Nessun costo nel percorso normale. */
        put("  ebx       = "); put_hex(cpu->_ebx);
        put("  esi       = "); put_hex(cpu->_esi);
        put("  edi       = "); put_hex(cpu->_edi);
        put("  ebp       = "); put_hex(cpu->_ebp);
        put("  eflags    = "); put_hex(cpu->_eflags);
        /* Pila emulata: una `ret` corrotta arriva qui con il chiamante NON piu' sullo stack, ma i
         * frame sottostanti contengono ancora gli indirizzi (host) delle continuazioni. Per ogni
         * parola si stampa anche il VA guest corrispondente, se la tabella lo conosce: e' la
         * catena dei chiamanti senza bisogno di un debugger (nessuna esposizione gdb). */
        {
            unsigned k;
            put("  pila emulata (parola -> VA guest se nota):\n");
            for (k = 0; k < 12u; ++k) {
                uint32_t w = cpu_llasm_read32(cpu->_esp + 4u * k);
                uint32_t gva = va_of_fn(w);
                put("    esp+");
                {
                    char d[4]; int j = 0, v = (int) (4u * k);
                    char t[4]; int n = 0;
                    if (!v) t[n++] = '0';
                    while (v) { t[n++] = (char) ('0' + v % 10); v /= 10; }
                    while (n) d[j++] = t[--n];
                    (void) write(2, d, (unsigned long) j);
                }
                put(" = "); put_hex(w);
                if (gva) { put("          -> VA "); put_hex(gva); }
            }
        }
    }
    put("  codice ARM del port: "); put_hex(g_arm_lo);
    put("  ... "); put_hex(g_arm_hi);
    put("  ultimi archi indiretti (dal piu' vecchio; target, ESP prima dell'arco, parola in cima):\n");
    {
        unsigned k;
        for (k = 0; k < RING_SIZE; ++k) {
            reasm_edge *e = &g_ring[(g_ring_i + k) & (RING_SIZE - 1u)];
            uint32_t gva;
            if (!e->target) continue;
            gva = va_of_fn(e->target);
            put("    -> "); put_hex(e->target);
            if (gva) { put("       (entry VA "); put_hex(gva); put(")\n"); }
            put("       esp="); put_hex(e->esp);
            put("       [esp]="); put_hex(e->word);
            put("       [esp-4]="); put_hex(e->wordm1);
            if (e->wordm1 == e->target) {
                put("       <- pop/ret: il target era in [esp-4], cioe' la parola appena poppata\n");
            } else if (e->word >= g_arm_lo && e->word < g_arm_hi) {
                uint32_t cva = va_of_fn(e->word);
                put("       <- call: continuazione pushata");
                if (cva) { put(", VA guest dopo la call = "); put_hex(cva); }
                put("\n");
            } else {
                put("       <- call indiretta con continuazione NON in .text\n");
            }
        }
    }
    put("  (nessuna ipotesi: il chiamante guest e il target sono qui sopra)\n");
    _exit(71);
}
