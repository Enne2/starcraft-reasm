#!/usr/bin/env python3
"""runtime/arm/gen_storm_ordinals.py — storm.dll ordinal -> guest VA table for the ARM runtime.

Source of truth: sc-reasm's `analysis/storm_ordinals.json` (ordinal + absolute VA for each
export of the original storm.dll). The translated storm image is restored at those very VAs
(0x15000000 base), so an import by ordinal is a plain guest VA — no C bridge, no reimplementation.

If the JSON is missing the script still emits a *valid but empty* table: the runtime then resolves
nothing and reports it, instead of inventing addresses.

Usage:
  gen_storm_ordinals.py --json <sc-reasm>/analysis/storm_ordinals.json \
      --out build/runtime-arm/storm_ordinals_arm.c
"""
import argparse
import json
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    entries = []
    dll = "storm.dll"
    try:
        d = json.load(open(a.json, encoding="utf-8"))
        dll = d.get("dll_name", dll)
        for e in d.get("exports", []):
            entries.append((int(e["ordinal"]), int(e["va"])))
    except FileNotFoundError:
        entries = []
    entries.sort()

    lines = []
    lines.append("/* GENERATED by runtime/arm/gen_storm_ordinals.py — do not edit.")
    lines.append(" * source: %s" % a.json)
    lines.append(" * dll: %s, exports: %d */" % (dll, len(entries)))
    lines.append('#include <stdint.h>')
    lines.append("")
    lines.append("typedef struct { uint32_t ordinal; uint32_t va; } ArmStormOrdinal;")
    lines.append("")
    if entries:
        lines.append("const ArmStormOrdinal g_storm_ordinals[] = {")
        for ordv, va in entries:
            lines.append("    { %uu, 0x%08Xu }," % (ordv, va))
        lines.append("};")
    else:
        # An empty initialiser is not valid C; one sentinel entry plus a count of 0 is.
        lines.append("const ArmStormOrdinal g_storm_ordinals[] = { { 0u, 0x00000000u } };")
    lines.append("const uint32_t g_storm_ordinals_n = %uu;" % len(entries))
    lines.append("")

    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("gen_storm_ordinals: %d ordinals -> %s" % (len(entries), a.out))


if __name__ == "__main__":
    sys.exit(main())
